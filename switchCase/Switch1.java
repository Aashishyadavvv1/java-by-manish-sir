class Switch1{
void main(){
	System.out.println("enter number");
	int number=new java.util.Scanner(System.in) .nextInt();
	switch(number)
	{
	case 1:
	System.out.println("sunday");
	break;
	case 2:
	System.out.println("monday");
	break;
	case 3:
	System.out.println("tuesday");
	break;
	default:
	System.out.println("holiday");
	break;
}
}

}